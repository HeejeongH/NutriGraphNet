def fmt(mu, sd, is_best, is_second, star):
    """수치 포맷 + bold/underline/star"""
    if mu is None:
        return r'--'
    cell = f'{mu:.4f}\\tiny{{$\\pm${sd:.4f}}}'
    if is_best:
        cell = r'\textbf{' + cell + '}'
    elif is_second:
        cell = r'\underline{' + cell + '}'
    if star == '**':
        cell += r'$^{**}$'
    elif star == '*':
        cell += r'$^{*}$'
    return cell

def best_second(data, metric):
    vals = [(data[v][metric][0], v) for v in data
            if data[v][metric][0] is not None]
    vals.sort(key=lambda x: x[0], reverse=True)
    b  = vals[0][0] if vals else None
    s  = vals[1][0] if len(vals) > 1 else None
    return b, s

